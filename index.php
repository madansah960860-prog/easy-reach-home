            <h2 id="story-title">Who this shop is for</h2>
          </div>
          <p>It is for anyone who would rather not hunt for their reading glasses to check what time
             it is. Anyone who has decided that a spoon handle the thickness of a pencil is a design
             choice nobody ever defended. Anyone tired of a bath mat that slides.</p>
          <p>That is a set of preferences, not a description of a person, and it is the only way we
             are going to talk about it. You will not find the word "senior" on this site, or
             "elderly", or "as we age", or anything about what you can no longer do. Plenty of people
             simply prefer a thicker handle and a bigger number, and that is reason enough for a shop
             to exist.</p>
          <p>What we do instead is publish the measurement. A 1.3-inch handle is a fact. Whether it
             suits you is yours to decide, and you are perfectly capable of deciding it.</p>
